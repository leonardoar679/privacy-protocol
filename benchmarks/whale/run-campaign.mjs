#!/usr/bin/env node
// Runs the campaign lab (packages/protocol/src/sim/campaignLab.ts, High-Value Protection spec §18) on the measured
// quotes of execution.json and writes campaign.json and campaign.md next to this file, with gas priced at the LIVE
// gas price and ETH/USD fetched by benchmarks/gas/cost.mjs when this runs (never a constant). Then it writes the route
// risk models the service's risk database reads (packages/swap-engine/risk/routes/<provider>-<pair>.json) from the
// same measured rows, dated. Usage: node run-campaign.mjs [--seed 4242] [--no-live]
import { spawnSync } from "child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const ref = join(root, "packages", "protocol");
const argv = process.argv.slice(2);
const noLive = argv.includes("--no-live");

let gwei = null, ethUsd = null;
if (!noLive) {
  const cost = spawnSync("node", [join(root, "benchmarks", "gas", "cost.mjs"), "--json"], { encoding: "utf8", shell: true });
  try { const j = JSON.parse(cost.stdout); gwei = j.gas?.gwei ?? null; ethUsd = j.eth?.usd ?? null; } catch { /* no live price: the lab reports gas units only */ }
  if (gwei === null || ethUsd === null) console.log("live gas price unavailable: gas is reported in units only");
  else console.log(`live gas price ${gwei.toFixed(3)} gwei, ETH $${ethUsd.toFixed(0)}`);
}
const args = ["tsx", "src/sim/campaignLab.ts", "--execution", join(here, "execution.json"), "--json", join(here, "campaign.json"), "--md", join(here, "campaign.md"), ...argv.filter((a) => a !== "--no-live")];
if (gwei !== null && ethUsd !== null) args.push("--gwei", String(gwei), "--eth-usd", String(ethUsd));
const r = spawnSync("npx", args, { cwd: ref, stdio: "inherit", shell: true });
if (r.status !== 0) process.exit(r.status ?? 1);

// the route risk models (spec §10): one file per measured provider × pair, from the execution rows
const execution = JSON.parse(readFileSync(join(here, "execution.json"), "utf8"));
const outDir = join(root, "packages", "swap-engine", "risk", "routes");
mkdirSync(outDir, { recursive: true });
const CLASS = { thorchain: "R5", chainflip: "R5", mayan: "R5", "near-intents": "R2", lifi: "R5", "uniswap-across": "R5" };
const byRoute = new Map();
for (const row of execution.rows) {
  if (!row.ok) continue;
  const key = `${row.provider}|${row.pair}`;
  const e = byRoute.get(key) ?? { provider: row.provider, pair: row.pair, points: [] };
  e.points.push({ usd: row.usd, variant: row.variant, etaSeconds: row.etaSeconds ?? null, parts: row.parts ?? null, impactBps: row.impactBps ?? null, costVsOracleBps: row.costVsOracleBps ?? null, limits: row.limits ?? null });
  byRoute.set(key, e);
}
let n = 0;
for (const e of byRoute.values()) {
  const [from, to] = e.pair.split(">");
  const file = join(outDir, `${e.provider}-${from.replace(/[^A-Za-z0-9]/g, "")}-${to.replace(/[^A-Za-z0-9]/g, "")}.json`.toLowerCase());
  const maxUsd = Math.max(...e.points.map((p) => p.usd));
  const impactAtMax = e.points.filter((p) => p.usd === maxUsd).map((p) => p.impactBps ?? 0)[0] ?? 0;
  const doc = {
    provider: e.provider, pair: e.pair, class: CLASS[e.provider] ?? "R5",
    measuredAt: execution.at, source: "benchmarks/whale/execution.json (the V2 execution lab, read-only quotes)",
    servedUpToUsd: maxUsd, impactBpsAtMax: impactAtMax,
    points: e.points.sort((a, b) => a.usd - b.usd),
    note: "generated by benchmarks/whale/run-campaign.mjs from measured quotes; the lab regenerates it — never edited by hand",
  };
  writeFileSync(file, JSON.stringify(doc, null, 2) + "\n");
  n++;
}
console.log(`${n} route risk models written to packages/swap-engine/risk/routes/`);
if (!existsSync(join(here, "campaign.md"))) process.exit(1);
