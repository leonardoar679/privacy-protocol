#!/usr/bin/env node
// Regenerate privacy-core/src/poseidon2_constants.rs from the normative TypeScript implementation
// (reference/typescript/src/poseidon2.ts, itself machine-extracted from barretenberg's
// poseidon2_params.hpp), so the Rust core never hand-types a round constant — the same rule the
// Python reference follows (reference/python/gen_constants.mjs). Run: node scripts/gen-poseidon2-rs.mjs
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../../reference/typescript/src/poseidon2.ts"), "utf8");
const dBlock = src.slice(src.indexOf("const D:"), src.indexOf("const RC:"));
const rcBlock = src.slice(src.indexOf("const RC:"), src.indexOf("const mod"));
const hexes = (s) => [...s.matchAll(/0x[0-9a-f]{64}n/g)].map((m) => m[0].slice(0, -1));
const D = hexes(dBlock);
const RC = hexes(rcBlock);
if (D.length !== 4 || RC.length !== 256) throw new Error(`unexpected constant counts ${D.length} ${RC.length}`);
const dec = (h) => BigInt(h).toString(10);

const rs = [
  "// GENERATED by scripts/gen-poseidon2-rs.mjs from reference/typescript/src/poseidon2.ts (UseArclite,",
  "// itself machine-extracted from barretenberg v5.2.0 poseidon2_params.hpp). Do not edit.",
  "use crate::field::Fr;",
  "use ark_ff::MontFp;",
  "",
  "/// Internal matrix diagonal (minus one), t = 4.",
  "pub const D: [Fr; 4] = [",
  ...D.map((h) => `    MontFp!("${dec(h)}"),`),
  "];",
  "",
  "/// 64 rounds x 4 lanes: rounds 0-3 and 60-63 are external (all lanes), 4-59 internal (lane 0 only).",
  "pub const RC: [Fr; 256] = [",
  ...RC.map((h) => `    MontFp!("${dec(h)}"),`),
  "];",
  "",
].join("\n");
writeFileSync(join(here, "../privacy-core/src/poseidon2_constants.rs"), rs);
console.log(`wrote poseidon2_constants.rs (D=${D.length}, RC=${RC.length})`);
