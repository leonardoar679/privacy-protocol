// The vendored prover (spec v3.0 §7.3; V7 Stage 6): every file under vendor/ hashes to VENDORED.md's table and the table
// names every file; the modules under src/prover/legacy are exactly the pinned originals with the listed replacements
// (each applied the number of times it says); the precompiled circuit is pinned to the circuit's sha256, carries no
// eval, and — when the artifacts are on this machine — is what the pinned circuit derives.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { describe, expect, it } from "vitest";
import { CIRCUIT_SHA256, compileCircuit, TEMPLATES_FILE } from "../scripts/compile-circuit.mjs";
import { checkLegacy, convertAll, FILES, VENDOR_DIR } from "../scripts/vendor.mjs";

const sha256 = (bytes: Buffer) => createHash("sha256").update(bytes).digest("hex");
const lf = (bytes: Buffer) => Buffer.from(bytes.toString("utf8").replace(/\r\n?/g, "\n"), "utf8");

function files(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) files(p, out);
    else out.push(p);
  }
  return out;
}

describe("the vendored originals", () => {
  const table = readFileSync(join(VENDOR_DIR, "VENDORED.md"), "utf8");
  const rows = [...table.matchAll(/^\| `([^`]+)` \| (\d+) \| `([0-9a-f]{64})` \|$/gm)].map((m) => ({ file: m[1], bytes: Number(m[2]), sha256: m[3] }));

  it("VENDORED.md names every vendored file, and every file hashes to its row (LF bytes)", () => {
    const onDisk = files(VENDOR_DIR)
      .map((p) => relative(VENDOR_DIR, p).replace(/\\/g, "/"))
      .filter((p) => p !== "VENDORED.md")
      .sort();
    expect(rows.map((r) => r.file).sort()).toEqual(onDisk);
    for (const r of rows) {
      const bytes = lf(readFileSync(join(VENDOR_DIR, r.file)));
      expect(sha256(bytes), r.file).toBe(r.sha256);
      expect(bytes.length, r.file).toBe(r.bytes);
    }
    expect(rows.length).toBe(21);
  });

  it("the modules under src/prover/legacy are the pinned originals with the listed replacements, each applied as many times as the list says", () => {
    expect(checkLegacy()).toEqual([]);
    const converted = convertAll();
    expect(converted.length).toBe(FILES.length);
    expect(FILES.length).toBe(15);
    for (const c of converted) {
      expect(c.text.startsWith(`// Generated by classic/scripts/vendor.mjs from classic/vendor/${c.spec.from} (sha256 ${c.sha256})`), c.spec.to).toBe(true);
      expect(rows.find((r) => r.file === c.spec.from)?.sha256, c.spec.from).toBe(c.sha256);
    }
  });

  it("no converted module requires a module, exports CommonJS, touches Buffer, or evals; websnark no longer asks for a window", () => {
    for (const { spec, text } of convertAll()) {
      // the code without the header and the line comments (the conversion's own notes mention eval)
      const body = text
        .split("\n")
        .slice(2)
        .join("\n")
        .replace(/^[ \t]*\/\/.*$/gm, "");
      // websnark's Node worker bootstrap keeps one require inside a string, run in a Node worker thread only
      const outsideStrings = body.replace(/"\(" \+ thread\.toString\(\)\+ "\)\(require\('worker_threads'\)\.parentPort\);"/, "");
      expect(outsideStrings, spec.to).not.toMatch(/\brequire\s*\(\s*["']/);
      expect(body, spec.to).not.toMatch(/\bmodule\.exports\b/);
      expect(body, spec.to).not.toMatch(/\bBuffer\./);
      expect(body, spec.to).not.toMatch(/\beval\s*\(/);
      if (spec.to === "groth16.js") expect(body).not.toMatch(/typeof\s*\(?\s*window/);
    }
  });
});

describe("the precompiled circuit", () => {
  it("is pinned to the circuit's sha256, carries the 39 templates and the one function, and no eval", async () => {
    const text = readFileSync(TEMPLATES_FILE, "utf8");
    expect(text.startsWith(`// Generated by classic/scripts/compile-circuit.mjs from the pinned circuit tornado.json (sha256 ${CIRCUIT_SHA256})`)).toBe(true);
    expect(text).not.toMatch(/\beval\s*\(/);
    const mod = (await import("../src/prover/generated/templates.js")) as {
      templates: Record<string, unknown>;
      functions: Record<string, unknown>;
      compiled: unknown;
    };
    expect(Object.keys(mod.templates).length).toBe(39);
    expect(Object.keys(mod.functions)).toEqual(["nbits"]);
    expect(mod.compiled).toEqual({ templates: mod.templates, functions: mod.functions });
  });

  it("is what the pinned circuit derives, when the circuit is on this machine (copy-artifacts.mjs)", () => {
    const r = compileCircuit({ write: false });
    if (r.skipped) console.info(`SKIP  ${r.skipped}`);
    else expect(r.problems).toEqual([]);
    expect(r.ok).toBe(true);
  });
});
