// The design tokens, copied from the Privacy Wallet (spec v3.0 §7.8): one visual identity, zero runtime sharing. The
// generated stylesheet carries the source's hash; `--check` (verify-all) fails when packages/ui's tokens moved on.
//   node scripts/tokens.mjs          write src/tokens.generated.css
//   node scripts/tokens.mjs --check  compare it with packages/ui/src/tokens/tokens.css
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
export const SOURCE = join(here, "..", "..", "packages", "ui", "src", "tokens", "tokens.css");
export const TARGET = join(here, "..", "src", "tokens.generated.css");

/** The stylesheet to write: the source's body under a header naming it and its sha256 (LF content). */
export function generated(source = SOURCE) {
  const css = readFileSync(source, "utf8").replace(/\r\n/g, "\n");
  const sha = createHash("sha256").update(css).digest("hex");
  const body = css.replace(/^\/\*[\s\S]*?\*\/\n/, "");
  return `/* Generated by classic/scripts/tokens.mjs from packages/ui/src/tokens/tokens.css (sha256 ${sha}): the Privacy Wallet's design tokens, one visual identity (spec v3.0 §7.8). Edit the TypeScript tokens in packages/ui, then run npm run tokens here. */\n${body}`;
}

/** Whether src/tokens.generated.css is what packages/ui's tokens generate now. */
export function checkTokens() {
  const want = generated();
  const have = existsSync(TARGET) ? readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n") : null;
  return have === want
    ? { ok: true, message: "classic/src/tokens.generated.css is up to date with packages/ui/src/tokens/tokens.css" }
    : { ok: false, message: "classic/src/tokens.generated.css differs from packages/ui/src/tokens/tokens.css (run npm run tokens in classic/)" };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const r = checkTokens();
    console.log(`${r.ok ? "PASS" : "FAIL"}  ${r.message}`);
    process.exit(r.ok ? 0 : 1);
  }
  writeFileSync(TARGET, generated());
  console.log("wrote classic/src/tokens.generated.css");
}
