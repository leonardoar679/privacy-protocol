// The original circuit, precompiled (spec v3.0 §7.3; V7 Stage 6). snarkjs 0.1's witness calculator `eval`s the 39
// templates and the one function the circuit file carries as JavaScript source — which the Classic app's content
// security policy forbids. This script reads the pinned circuit (public/artifacts/tornado.json, copy-artifacts.mjs),
// writes those bodies as a static module, src/prover/generated/templates.js (committed, pinned to the circuit's
// sha256 in its header), and writes the rest of what the witness calculator reads — the signal map, the components,
// the signals with their trigger lists, the counts; never the 28,275 constraints — as public/artifacts/witness.json
// (served, pinned in src/prover/artifacts.json and its served copy). `--check` regenerates the module and compares it with the committed one.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ARTIFACT_DIR, readPins, writePins } from "./copy-artifacts.mjs";

const here = fileURLToPath(new URL(".", import.meta.url));
export const CIRCUIT_FILE = join(ARTIFACT_DIR, "tornado.json");
export const WITNESS_FILE = join(ARTIFACT_DIR, "witness.json");
export const TEMPLATES_FILE = join(here, "..", "src", "prover", "generated", "templates.js");
export const CIRCUIT_SHA256 = "3ddd61dbff09caeec82d8edde95c674a3c34f9e66b1fe9f2c8783e72fe536f98";
const sha256Hex = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** The circuit fields the witness calculator reads (snarkjs 0.1 circuit.js / calculateWitness.js), without the constraints. */
export const WITNESS_FIELDS = Object.freeze([
  "nPubInputs",
  "nPrvInputs",
  "nInputs",
  "nOutputs",
  "nVars",
  "nSignals",
  "nConstants",
  "signalName2Idx",
  "componentName2Idx",
  "components",
  "signals",
]);

export function readCircuit(file = CIRCUIT_FILE) {
  if (!existsSync(file)) return null;
  const bytes = readFileSync(file);
  const sha = sha256Hex(bytes);
  if (sha !== CIRCUIT_SHA256) throw new Error(`${file}: sha256 ${sha}, not the pinned ${CIRCUIT_SHA256}: refused`);
  return JSON.parse(bytes.toString("utf8"));
}

/** The static module: every template and function body verbatim, under the two constants their code reads. */
export function templatesModule(circuit, sha = CIRCUIT_SHA256) {
  const names = Object.keys(circuit.templates).sort();
  const functions = Object.keys(circuit.functions).sort();
  const lines = [
    `// Generated by classic/scripts/compile-circuit.mjs from the pinned circuit tornado.json (sha256 ${sha}): the ${names.length}`,
    `// templates and ${functions.length} function${functions.length === 1 ? "" : "s"} snarkjs 0.1 would eval at run time, as static code — the bodies verbatim, under the`,
    "// two constants they read (__P__, __MASK__, as circuit.js defines them). Do not edit; run the script after a circuit change.",
    'import bigInt from "../legacy/bigint.js";',
    "",
    'const __P__ = bigInt("21888242871839275222246405745257275088548364400416034343698204186575808495617");',
    'const __MASK__ = bigInt("28948022309329048855892746252171976963317496166410141009864396001978282409983");',
    "",
    "export const templates = {",
  ];
  for (const n of names) lines.push(`  ${JSON.stringify(n)}: ${circuit.templates[n]},`);
  lines.push("};", "", "export const functions = {");
  for (const f of functions)
    lines.push(`  ${JSON.stringify(f)}: { params: ${JSON.stringify(circuit.functions[f].params)}, func: ${circuit.functions[f].func} },`);
  lines.push("};", "", "export const compiled = { templates, functions };", "");
  return lines.join("\n");
}

export function witnessJson(circuit) {
  const out = {};
  for (const k of WITNESS_FIELDS) out[k] = circuit[k];
  return JSON.stringify(out);
}

export function compileCircuit({ write = true } = {}) {
  const circuit = readCircuit();
  if (!circuit) return { ok: true, skipped: "public/artifacts/tornado.json is not on this machine (copy-artifacts.mjs)" };
  const module = templatesModule(circuit);
  const problems = [];
  if (write) {
    mkdirSync(join(TEMPLATES_FILE, ".."), { recursive: true });
    writeFileSync(TEMPLATES_FILE, module);
    const witness = Buffer.from(witnessJson(circuit), "utf8");
    writeFileSync(WITNESS_FILE, witness);
    const pins = readPins();
    pins.files["witness.json"] = { sha256: sha256Hex(witness), bytes: witness.length };
    writePins(pins);
  } else {
    if (!existsSync(TEMPLATES_FILE)) problems.push("src/prover/generated/templates.js is missing (compile-circuit.mjs)");
    else if (readFileSync(TEMPLATES_FILE, "utf8") !== module) problems.push("src/prover/generated/templates.js differs from the pinned circuit's templates");
    if (existsSync(WITNESS_FILE)) {
      const pin = readPins().files["witness.json"];
      const sha = sha256Hex(readFileSync(WITNESS_FILE));
      if (!pin || pin.sha256 !== sha) problems.push("public/artifacts/witness.json does not hash to its pin");
      if (sha !== sha256Hex(Buffer.from(witnessJson(circuit), "utf8"))) problems.push("public/artifacts/witness.json is not what the pinned circuit derives");
    }
  }
  return { ok: problems.length === 0, problems, templates: Object.keys(circuit.templates).length, functions: Object.keys(circuit.functions).length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = compileCircuit({ write: !process.argv.includes("--check") });
  if (r.skipped) console.log(`SKIP  ${r.skipped}`);
  else {
    for (const p of r.problems ?? []) console.error(`FAIL  ${p}`);
    if (r.ok)
      console.log(
        `PASS  circuit: ${r.templates} templates and ${r.functions} function precompiled; the witness file ${process.argv.includes("--check") ? "matches its pin" : "written and pinned"}`,
      );
  }
  process.exit(r.ok ? 0 : 1);
}
