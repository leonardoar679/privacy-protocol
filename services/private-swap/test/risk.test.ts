    expect(p.estimatedTranches).toBeLessThanOrEqual(55);
    expect(p.capUsd).toBe(200_000);
    expect(p.trancheUsd![1]).toBeLessThanOrEqual(200_000);
    expect(p.trancheUsd![0]).toBeGreaterThan(0);
    expect(p.concentration).toEqual({ providers: [{ id: "thorchain", shareBps: 10000 }], singleVenue: true, capBps: 10000 });
    expect(p.elpf.prior).toBe(0.02);
    expect(p.elpf.perCampaignUsd).toBeCloseTo(0.02 * 200_000, 3); // 145 days after the incident the factor is 1 (it is 1.5 inside 90 days)
    expect(p.elpf.perTrancheUsd).toBeLessThanOrEqual(p.elpf.perCampaignUsd!);
    expect(p.trancheImpactBps).toBeCloseTo(0.18, 2); // 9 bps for the whole, scaled to one 2 % piece
    expect(p.estimatedSeconds).toBeGreaterThan(p.estimatedTranches * (3600 + 600)); // the Bitcoin finality margin and the cadence per step
    expect(p.cadenceSeconds).toEqual(CADENCE_SECONDS.balanced);
    expect(p.reasons.join("\n")).toMatch(/one piece at a time/);
