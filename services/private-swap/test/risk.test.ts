    shaky.health.thorchain = ok("thorchain", { halted: true });
    expect(recommendProtection({ set: shaky, req: reqEthBtc(small), amount: small, tier: "enhanced", mode: "balanced", usdPerUnit: ETH_USD, db, now: NOW })!.staged).toBe(true);
    // USDC legs carry the issuer flag; nothing chosen → nothing recommended; below the enhanced tier nothing is attached
