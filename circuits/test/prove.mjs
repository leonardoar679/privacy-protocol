// Groth16 proof/verifier consistency harness over the DEV setup (scripts/dev-setup.sh) — the method
// the Tornado study executed in research/09-testing/proof-verifier, applied to this circuit: a real
// proof verifies; changing ANY single public input, or pairing it with another transaction's public
// inputs, does not. It also pins the public-signal ORDER to PrivacyCore.encodePublicInputs and emits
// Solidity calldata fixtures for the on-chain verifier test (contracts/test/verifier).
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import * as snarkjs from "snarkjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const R = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const WASM = join(root, "build/transaction_js/transaction.wasm");
const ZKEY = join(root, "build/setup/transaction_final.zkey");
const FIXTURES_SOL = join(root, "../contracts/test/verifier/DevProofFixtures.sol");
const vk = JSON.parse(readFileSync(join(root, "setup/dev/verification_key.json"), "utf8"));
const load = (name) => JSON.parse(readFileSync(join(root, "test/fixtures/v1", `${name}.json`), "utf8"));

// The vector PrivacyCore.encodePublicInputs builds, field by field (spec §11).
const encodePublicInputs = (i) => [
  i.root, ...i.nullifier, ...i.outputBody, i.mode, i.withdrawalVault, i.withdrawalAmount,
  i.withdrawalRecipient, ...i.outDataHash, i.txDomain,
];

let total = 0;
let failed = 0;
const check = (ok, label) => {
  total++;
  if (!ok) failed++;
  console.log(`${ok ? "PASS" : "FAIL"}  ${label}`);
};

const proofs = {};
for (const name of ["ok-transfer", "ok-withdraw", "ok-two-inputs", "ok-relayer-fee"]) {
  const input = load(name);
  const t0 = Date.now();
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, WASM, ZKEY);
  const ms = Date.now() - t0;
  proofs[name] = { proof, publicSignals };

  check(JSON.stringify(publicSignals) === JSON.stringify(encodePublicInputs(input)),
    `${name}: public signals == PrivacyCore.encodePublicInputs (${publicSignals.length} fields, same order)`);
  check(await snarkjs.groth16.verify(vk, publicSignals, proof), `${name}: proof verifies (proved in ${ms} ms)`);

  let rejected = 0;
  for (let k = 0; k < publicSignals.length; k++) {
    const tampered = [...publicSignals];
    tampered[k] = ((BigInt(tampered[k]) + 1n) % R).toString();
    if (!(await snarkjs.groth16.verify(vk, tampered, proof))) rejected++;
  }
  check(rejected === publicSignals.length,
    `${name}: changing any single public input is rejected (${rejected}/${publicSignals.length})`);
}

check(!(await snarkjs.groth16.verify(vk, proofs["ok-withdraw"].publicSignals, proofs["ok-transfer"].proof)),
  "a transfer proof does not verify against the withdraw's public inputs");
check(!(await snarkjs.groth16.verify(vk, proofs["ok-transfer"].publicSignals, proofs["ok-withdraw"].proof)),
  "a withdraw proof does not verify against the transfer's public inputs");

// Solidity fixtures: the exact calldata the on-chain verifier consumes (G2 limbs EVM-ordered).
async function solFixture(fn, { proof, publicSignals }) {
  const [a, b, c, pub] = JSON.parse(`[${await snarkjs.groth16.exportSolidityCallData(proof, publicSignals)}]`);
  const arr = (xs) => `[uint256(${xs[0]}), ${xs.slice(1).join(", ")}]`;
  return [
    `    function ${fn}() internal pure returns (Fixture memory f) {`,
    `        f.a = ${arr(a)};`,
    `        f.b = [${arr(b[0])}, ${arr(b[1])}];`,
    `        f.c = ${arr(c)};`,
    `        f.pub = ${arr(pub)};`,
    `    }`,
  ].join("\n");
}
writeFileSync(FIXTURES_SOL, [
  "// SPDX-License-Identifier: MIT",
  "pragma solidity ^0.8.24;",
  "",
  "// GENERATED by circuits/test/prove.mjs — DO NOT EDIT. Real Groth16 proofs of circuits/transaction.circom",
  "// for test/fixtures/v1/{ok-transfer,ok-withdraw}, under the INSECURE dev setup (scripts/dev-setup.sh).",
  "// Proofs are randomized, so regenerating changes the bytes; they stay valid for the same dev key.",
  "library DevProofFixtures {",
  "    struct Fixture {",
  "        uint256[2] a;",
  "        uint256[2][2] b;",
  "        uint256[2] c;",
  "        uint256[14] pub;",
  "    }",
  "",
  await solFixture("transfer", proofs["ok-transfer"]),
  "",
  await solFixture("withdraw", proofs["ok-withdraw"]),
  "}",
  "",
].join("\n"));
console.log(`\nwrote ${FIXTURES_SOL}`);
console.log(`proof harness: ${total - failed}/${total} checks passed`);
process.exit(failed ? 1 : 0); // ffjavascript keeps worker threads alive; exit explicitly
