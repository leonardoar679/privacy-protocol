// Prove the end-to-end witnesses (test/fixtures/e2e, built by reference/typescript genE2EInputs.ts
// for the forge deployment) and emit contracts/test/e2e/E2EFixture.sol: two transactions (Alice's
// withdrawal with a private relayer-fee note; the relayer spending it), their payloads and the roots.
// `--stub` writes an all-zero fixture so the contracts compile before the first generation.
// Driven by scripts/e2e-fixture.sh.
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import * as snarkjs from "snarkjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "../contracts/test/e2e/E2EFixture.sol");
const stub = process.argv.includes("--stub");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const NOTE_DATA_BYTES = 169;

let meta;
let txs;
if (stub) {
  const z = "0x" + "00".repeat(NOTE_DATA_BYTES);
  meta = {
    vaultId: 0, aliceOwnerCommitment: 0, aliceNoteSecret: 0, recipient: 0, relayer: 0, deposit: 0, withdrawal: 0,
    fee: 0, root: 0, rootAfter: 0, rootAfter2: 0, depositNoteData: z, noteData: [[z, z, z], [z, z, z]],
  };
  txs = [0, 1].map(() => ({ a: [0, 0], b: [[0, 0], [0, 0]], c: [0, 0], pub: Array(14).fill(0) }));
} else {
  meta = read("test/fixtures/e2e/meta.json");
  const vk = read("setup/dev/verification_key.json");
  txs = [];
  for (const name of ["tx1", "tx2"]) {
    const { proof, publicSignals } = await snarkjs.groth16.fullProve(
      read(`test/fixtures/e2e/${name}.json`),
      join(root, "build/transaction_js/transaction.wasm"),
      join(root, "build/setup/transaction_final.zkey"),
    );
    if (!(await snarkjs.groth16.verify(vk, publicSignals, proof))) throw new Error(`${name} proof does not verify`);
    const [a, b, c, pub] = JSON.parse(`[${await snarkjs.groth16.exportSolidityCallData(proof, publicSignals)}]`);
    txs.push({ a, b, c, pub });
  }
}

const arr = (xs) => `[uint256(${xs[0]}), ${xs.slice(1).join(", ")}]`;
const hexLit = (h) => `hex"${h.replace(/^0x/, "")}"`;
const branch = (t, body) => `        if (t == ${t}) {\n${body}\n        }`;
const proofBranch = (t) => branch(t, [
  `            a = ${arr(txs[t].a)};`,
  `            b = [${arr(txs[t].b[0])}, ${arr(txs[t].b[1])}];`,
  `            c = ${arr(txs[t].c)};`,
].join("\n"));
const pubBranch = (t) => branch(t, `            p = ${arr(txs[t].pub)};`);
const noteDataBranch = (t) => branch(t, [0, 1, 2].map((k) =>
  `            if (k == ${k}) return ${hexLit(meta.noteData[t][k])};`).join("\n"));

writeFileSync(OUT, `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// GENERATED by circuits/scripts/e2e-fixture.sh — DO NOT EDIT.
// ${stub
  ? "STUB (all zero): run circuits/scripts/e2e-fixture.sh before the e2e tests can pass."
  : "Real Groth16 proofs (INSECURE dev setup) of the e2e transactions, built for RealProofE2E.t.sol's deployment."}
library E2EFixture {
    uint256 internal constant VAULT_ID = ${meta.vaultId};
    uint256 internal constant ALICE_OWNER_COMMITMENT = ${meta.aliceOwnerCommitment};
    uint256 internal constant ALICE_NOTE_SECRET = ${meta.aliceNoteSecret};
    uint256 internal constant RECIPIENT = ${meta.recipient};
    uint256 internal constant RELAYER = ${meta.relayer};
    uint256 internal constant DEPOSIT = ${meta.deposit};
    uint256 internal constant WITHDRAWAL = ${meta.withdrawal};
    uint256 internal constant FEE = ${meta.fee};
    uint256 internal constant ROOT = ${meta.root};
    uint256 internal constant ROOT_AFTER = ${meta.rootAfter};
    uint256 internal constant ROOT_AFTER_2 = ${meta.rootAfter2};

    function depositNoteData() internal pure returns (bytes memory) {
        return ${hexLit(meta.depositNoteData)};
    }

    /// Fixed-size output payload k of transaction t.
    function noteData(uint8 t, uint8 k) internal pure returns (bytes memory) {
${noteDataBranch(0)}
${noteDataBranch(1)}
        revert("no such payload");
    }

    function proof(uint8 t) internal pure returns (uint256[2] memory a, uint256[2][2] memory b, uint256[2] memory c) {
${proofBranch(0)}
${proofBranch(1)}
    }

    function pub(uint8 t) internal pure returns (uint256[14] memory p) {
${pubBranch(0)}
${pubBranch(1)}
    }
}
`);
console.log(`wrote ${OUT}${stub ? " (stub)" : ""}`);
process.exit(0); // ffjavascript keeps worker threads alive
