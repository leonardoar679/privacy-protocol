// Witness-level soundness harness. Every fixture in test/fixtures/manifest.json is fed to its compiled
// circuit: honest fixtures must be satisfiable, attacks must not. The v0-draft fixtures run against
// test/regressions/transaction_v0_draft.circom and reproduce findings PP-C01/PP-C02.
// Prereq: `npm run fixtures` in reference/typescript, then compile both circuits (see README).
import { readFileSync } from "fs";
import { createRequire } from "module";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const circuit = {
  "v1": ["build/transaction_js", "transaction.wasm"],
  "v0-draft": ["build/transaction_v0_draft_js", "transaction_v0_draft.wasm"],
};

// A fresh instance per fixture, so an aborted (unsatisfiable) witness cannot leak state.
async function satisfiable(schema, inputs) {
  const [dir, wasm] = circuit[schema];
  const builder = require(join(root, dir, "witness_calculator.js"));
  const calc = await builder(readFileSync(join(root, dir, wasm)));
  try {
    await calc.calculateWitness(inputs, true);
    return { sat: true };
  } catch (e) {
    // circom appends "Error in template <T> line: <N>" — the exact constraint that failed.
    return { sat: false, why: String(e.message ?? e).split("\n").map((l) => l.trim()).filter(Boolean).join(" | ") };
  }
}

const only = process.argv[2]; // optional schema filter: v1 | v0-draft
// v1 fixtures are regenerated by reference/typescript (`npm run fixtures`); the v0-draft regression
// fixtures are static (the draft's note format no longer exists in the reference).
const manifest = [
  ...JSON.parse(readFileSync(join(root, "test/fixtures/manifest.json"), "utf8")),
  ...JSON.parse(readFileSync(join(root, "test/fixtures/v0-draft/manifest.json"), "utf8")),
].filter((e) => !only || e.schema === only);
const load = (e) => JSON.parse(readFileSync(join(root, "test/fixtures", e.schema, `${e.name}.json`), "utf8"));

let failed = 0;
for (const e of manifest) {
  const r = await satisfiable(e.schema, load(e));
  const ok = r.sat === (e.expect === "sat");
  if (!ok) failed++;
  console.log(
    `${ok ? "PASS" : "FAIL"}  ${e.schema.padEnd(8)} ${e.name.padEnd(28)} ${(r.sat ? "SAT" : "UNSAT").padEnd(5)}  ${e.rule}` +
      (r.sat ? "" : `\n        -> ${r.why}`),
  );
}

// PP-C01/PP-C02 evidence from the draft: one leaf, several accepted spends.
const draft = manifest.filter((e) => e.schema === "v0-draft").map((e) => ({ name: e.name, ...load(e) }));
if (draft.length) {
  console.log("\nDraft circuit evidence (all spend leaf 0 under the same root):");
  for (const d of draft) console.log(`  ${d.name.padEnd(18)} key=${d.inOwnerKey[0].slice(0, 12)}…  nullifier[0]=${d.nullifier[0].slice(0, 16)}…  nullifier[1]=${d.nullifier[1].slice(0, 16)}…`);
  const sameRoot = new Set(draft.map((d) => d.root)).size === 1;
  const nf0 = new Set(draft.map((d) => d.nullifier[0])).size;
  const nf1 = new Set(draft.map((d) => d.nullifier[1])).size;
  console.log(`  PP-C01: ${draft.length} accepted spends of one note -> ${nf0} distinct nullifiers (same root: ${sameRoot})`);
  console.log(`  PP-C02: phantom nullifier[1] takes ${nf1} distinct value(s) across ${draft.length} transactions`);
}

console.log(`\nwitness harness: ${manifest.length - failed}/${manifest.length} fixtures behaved as expected`);
process.exit(failed ? 1 : 0);
