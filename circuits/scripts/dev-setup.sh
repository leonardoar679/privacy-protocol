#!/usr/bin/env bash
# Deterministic, INSECURE-BY-DESIGN Groth16 (BN254) setup for transaction.circom.
# Every contribution is a PUBLIC beacon, so anyone can recompute the toxic waste and forge proofs
# against this key. It exists only so the proof pipeline (prove -> verify -> on-chain verifier) is
# testable and byte-for-byte reproducible. (snarkjs `contribute` always mixes in OS randomness, so
# beacons are the only reproducible contribution.) A production key needs a multi-party ceremony
# (spec §56) and a fresh verifier.
#
# Prereq: build/transaction.r1cs   (circom transaction.circom --r1cs --wasm --sym --O2 -l node_modules -o build)
# Output: setup/dev/verification_key.json, ../contracts/src/verifier/dev/TransactionVerifierDev.sol
set -euo pipefail
cd "$(dirname "$0")/.."

SNARKJS="node node_modules/snarkjs/build/cli.cjs"
POWER=15 # 2^15 = 32,768 >= the r1cs's 23,343 constraints (+ 14 public inputs), compiled with --O2
BEACON=$(printf '%s' 'privacy-protocol/v1/dev-setup/INSECURE-PUBLIC-BEACON' | sha256sum | cut -d' ' -f1)
OUT=build/setup
VERIFIER=../contracts/src/verifier/dev/TransactionVerifierDev.sol
mkdir -p "$OUT" setup/dev "$(dirname "$VERIFIER")"

echo "beacon = $BEACON"
$SNARKJS powersoftau new bn128 $POWER $OUT/pot_0000.ptau
$SNARKJS powersoftau beacon $OUT/pot_0000.ptau $OUT/pot_beacon.ptau "$BEACON" 10 -n="dev beacon (public, insecure)"
$SNARKJS powersoftau prepare phase2 $OUT/pot_beacon.ptau $OUT/pot_final.ptau
$SNARKJS groth16 setup build/transaction.r1cs $OUT/pot_final.ptau $OUT/transaction_0000.zkey
$SNARKJS zkey beacon $OUT/transaction_0000.zkey $OUT/transaction_final.zkey "$BEACON" 10 -n="dev zkey beacon (public, insecure)"
$SNARKJS zkey verify build/transaction.r1cs $OUT/pot_final.ptau $OUT/transaction_final.zkey
$SNARKJS zkey export verificationkey $OUT/transaction_final.zkey setup/dev/verification_key.json
$SNARKJS zkey export solidityverifier $OUT/transaction_final.zkey $OUT/verifier.sol

{
  echo "// SPDX-License-Identifier: GPL-3.0"
  echo "// ============================================================================================"
  echo "// GENERATED by circuits/scripts/dev-setup.sh (snarkjs) — DO NOT EDIT."
  echo "// INSECURE BY DESIGN: the setup's only contributions are PUBLIC beacons, so anyone can derive"
  echo "// the toxic waste and forge proofs for this key. For tests only; NEVER deploy. A production"
  echo "// verifier must come from a multi-party ceremony over the finalized circuit (spec §56)."
  echo "// ============================================================================================"
  grep -v 'SPDX-License-Identifier' "$OUT/verifier.sol" | sed 's/contract Groth16Verifier/contract TransactionVerifierDev/'
} > "$VERIFIER"
echo "wrote setup/dev/verification_key.json and $VERIFIER"
