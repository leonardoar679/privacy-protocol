// Regenerate poseidon2_constants.py from the vendored TypeScript implementation, so the Python
// reference never hand-types a round constant. Run: node gen_constants.mjs
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../packages/protocol/src/poseidon2.ts"), "utf8");
const dBlock = src.slice(src.indexOf("const D:"), src.indexOf("const RC:"));
const rcBlock = src.slice(src.indexOf("const RC:"), src.indexOf("const mod"));
const hexes = (s) => [...s.matchAll(/0x[0-9a-f]{64}n/g)].map((m) => m[0].slice(0, -1));
const D = hexes(dBlock);
const RC = hexes(rcBlock);
if (D.length !== 4 || RC.length !== 256) throw new Error(`unexpected constant counts ${D.length} ${RC.length}`);

const py = [
  "# GENERATED by gen_constants.mjs from packages/protocol/src/poseidon2.ts (UseArclite, itself",
  "# machine-extracted from barretenberg v5.2.0 poseidon2_params.hpp). Do not edit.",
  "# Internal matrix diagonal (minus one), t = 4.",
  "D = [",
  ...D.map((h) => `    ${h},`),
  "]",
  "",
  "# 64 rounds x 4 lanes: rounds 0-3 and 60-63 are external (all lanes), 4-59 internal (lane 0 only).",
  "RC = [",
  ...RC.map((h) => `    ${h},`),
  "]",
  "",
].join("\n");
writeFileSync(join(here, "poseidon2_constants.py"), py);
console.log(`wrote poseidon2_constants.py (D=${D.length}, RC=${RC.length})`);
