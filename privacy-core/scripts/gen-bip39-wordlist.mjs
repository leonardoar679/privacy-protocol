#!/usr/bin/env node
// Embed the BIP-39 English wordlist into the Rust core from the same package the web wallet uses
// (@scure/bip39), so the two implementations cannot drift. Run: node scripts/gen-bip39-wordlist.mjs
import { createHash } from "crypto";
import { writeFileSync } from "fs";
import { createRequire } from "module";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "../../apps/web/package.json"));
const { wordlist } = require("@scure/bip39/wordlists/english");
if (wordlist.length !== 2048) throw new Error(`expected 2048 words, got ${wordlist.length}`);
const digest = createHash("sha256").update(wordlist.join("\n")).digest("hex");
const rs = [
  "// GENERATED by scripts/gen-bip39-wordlist.mjs from @scure/bip39/wordlists/english (the web wallet's list). Do not edit.",
  `// sha256 of the newline-joined list: ${digest}`,
  "pub const WORDLIST: [&str; 2048] = [",
  ...wordlist.map((w) => `    "${w}",`),
  "];",
  "",
].join("\n");
writeFileSync(join(here, "../privacy-core/src/wallet/bip39_wordlist.rs"), rs);
console.log(`wrote bip39_wordlist.rs (2048 words, sha256 ${digest.slice(0, 16)}…)`);
